export function zoneAt(x, z) {
  for (const [id, zn] of Object.entries(ZONES)) {
    if (!zn.modal) continue
    if (Math.hypot(x - zn.center[0], z - zn.center[1]) < zn.radius) return id
  }
  return null
}
