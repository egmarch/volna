// [cx, cz, w, d] — стены (axis-aligned)
const wall = (x1, z1, x2, z2, t = 0.4) => [
  (x1 + x2) / 2,
  (z1 + z2) / 2,
  Math.abs(x2 - x1) || t,
  Math.abs(z2 - z1) || t,
]

